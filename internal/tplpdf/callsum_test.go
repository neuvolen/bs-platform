func TestRenderCallSummary(t *testing.T) {
	b, err := RenderCallSummary(sampleCall())
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(b, []byte("%PDF-")) || !bytes.Contains(b, []byte("%%EOF")) || len(b) < 20000 {
		t.Fatalf("not a pdf: %d", len(b))
	}
	if out := os.Getenv("TPL_OUT"); out != "" {
		_ = os.WriteFile(filepath.Join(out, "call_summary.pdf"), b, 0o644)
	}
	// Only a summary text, no lists: still a valid PDF.
	if _, err := RenderCallSummary(&CallDoc{Summary: "Коротко."}); err != nil {
		t.Fatal(err)
	}
	if _, err := RenderCallSummary(&CallDoc{}); err == nil {
		t.Fatal("an empty call must fail")
	}
}

