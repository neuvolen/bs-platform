var threadsReachByID = func() map[string]*threadsFormat {
	m := map[string]*threadsFormat{}
	for i := range threadsReachFormats {
		m[threadsReachFormats[i].ID] = &threadsReachFormats[i]
	}
	return m
}()

func init() {
	for i := range threadsReachFormats {
		threadsFormatByID[threadsReachFormats[i].ID] = &threadsReachFormats[i]
	}
}

// threadsReach: the share of reach posts, %: unset 65, 0 off, at most 80.
func (s contentSettings) threadsReach() int {
	p := s.Channels.Threads.ReachPct
	if p == nil {
		return threadsReachDef
	}
	if *p <= 0 {
		return 0
	}
	if *p > threadsReachMax {
		return threadsReachMax
	}
	return *p
}

// threadsReachCount: how many of n posts are reach posts (n >= 2 keeps one
// trust post for the CTA).
func threadsReachCount(n, pct int) int {
	if pct <= 0 || n < 1 {
		return 0
	}
	r := int(math.Round(float64(n*pct) / 100))
	if r < 1 {
		r = 1
	}
	if n >= 2 && r > n-1 {
		r = n - 1
	}
	if r > n {
		r = n
	}
	return r
}

// threadsDayPlan: the formats of a day's n slots and which end with the CTA.
// pct 0: the classic plan. Otherwise reach slots are spread evenly (the day
// opens with one), the reach rubrics take turns in a day-dependent order, the
// trust slots keep the classic weights, and only trust slots get the CTA.
func threadsDayPlan(n int, key string, pct int) ([]string, []bool) {
	r := threadsReachCount(n, pct)
	if r == 0 {
		f := threadsDayFormats(n, key)
		return f, threadsCTASlots(n, f)
	}
	isReach := make([]bool, n)
	for k := 0; k < r; k++ {
		isReach[k*n/r] = true
	}
	ids := make([]string, len(threadsReachFormats))
	for i, f := range threadsReachFormats {
		ids[i] = f.ID
	}
	sort.SliceStable(ids, func(a, b int) bool { return hashN(key+"/r/"+ids[a], 997) < hashN(key+"/r/"+ids[b], 997) })
	trust := []string{}
	if n-r > 0 {
		trust = threadsDayFormats(n-r, key)
	}
	out := make([]string, n)
	ri, ti := 0, 0
	for i := 0; i < n; i++ {
		if isReach[i] {
			out[i] = ids[ri%len(ids)]
			ri++
		} else {
			out[i] = trust[ti]
			ti++
		}
	}
	// CTA: on trust slots only (never a question), about 1 in 8 posts, at least 1
	cta := make([]bool, n)
	var slots []int
	for i := 1; i < n; i++ {
		if !isReach[i] && out[i] != "question" {
			slots = append(slots, i)
		}
	}
	want := (n + 4) / 8
	if want < 1 {
		want = 1
	}
	if want > len(slots) {
		want = len(slots)
	}
	for k := 0; k < want; k++ {
		cta[slots[(k*len(slots))/want+len(slots)/(2*want)]] = true
	}
	return out, cta
}

// IsThreadsReach: the format is a reach rubric (the platform shows it apart).
func IsThreadsReach(id string) bool { return threadsReachByID[id] != nil }

