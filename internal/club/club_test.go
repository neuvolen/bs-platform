func TestMoneyAndDate(t *testing.T) {
	for in, want := range map[string]int64{"10,000": 10000, "-39,590": -39590, "1 000 000": 1000000, "": 0, "—": 0, "0.6": 1, "300 248": 300248} {
		if got, ok := Money(in); !ok || got != want {
			t.Errorf("Money(%q) = %d, %v; want %d", in, got, ok, want)
		}
	}
	if _, ok := Money("abc"); ok {
		t.Error("Money(abc) accepted")
	}
	cases := map[string]string{
		"20.08.2025":            "2025-08-20 00:00",
		"22.09.2026 23:19":      "2026-09-22 23:19",
		"9/18/2026 12:00:00":    "2026-09-18 12:00",
		"2026-08-18 16:29:05.9": "2026-08-18 16:29",
	}
	for in, want := range cases {
		d, ok := Date(in)
		if !ok || d.Format("2006-01-02 15:04") != want || d.Location() != Almaty {
			t.Errorf("Date(%q) = %v, %v; want %s Almaty", in, d, ok, want)
		}
	}
	if _, ok := Date("31.13.2026"); ok {
		t.Error("month 13 accepted")
	}
	if ClockTime("9:00") != "09:00" || ClockTime("15:00:00") != "15:00" || ClockTime("x") != "" {
		t.Error("ClockTime wrong")
	}
}

