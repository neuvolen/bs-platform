func TestParseAndCheck(t *testing.T) {
	snap, warn, err := Parse(sheetsFixture())
	if err != nil {
		t.Fatal(err)
	}
	if len(snap.Residents) != 3 {
		t.Fatalf("residents: %d (%+v)", len(snap.Residents), snap.Residents)
	}
	ivan, petr, old := snap.Residents[0], snap.Residents[1], snap.Residents[2]
	if ivan.TgID != 111222333 || ivan.Granted != 3 || ivan.Done != 1 || ivan.RestEntry != 50000 || ivan.JoinedAt == nil {
		t.Errorf("Иван прочитан неверно: %+v", ivan)
	}
	if petr.TgID != 444555666 || !petr.Exception || petr.Partner != "Иван Тест" {
		t.Errorf("Пётр: Chat ID с «.0» должен остаться 444555666, получено %+v", petr)
	}
	if !old.Former || old.Name != "Старый" || old.LeftAt == nil || old.PaidEntry != 250000 {
		t.Errorf("бывший прочитан неверно: %+v", old)
	}
	if len(snap.Payments) != 7 || !snap.Payments[0].Applied {
		t.Errorf("ДДС: %d строк", len(snap.Payments))
	}
	if len(warn) != 1 {
		t.Errorf("ждал одно предупреждение (строка «не дата»), получил %v", warn)
	}
	if len(snap.Meetings) != 2 || snap.Meetings[0].Online || snap.Meetings[0].Place != "г.Алматы, Достык 44" ||
		!snap.Meetings[1].Online || !snap.Meetings[1].Done || snap.Meetings[1].EventID != "ev123" || snap.Meetings[1].Time != "09:00" {
		t.Errorf("расписание прочитано неверно: %+v", snap.Meetings)
	}
	if len(snap.Reports) != 2 || snap.Reports[0].At.Unix() != 1790101199 || !snap.Reports[1].Late {
		t.Errorf("лог отчётов: %+v", snap.Reports)
	}
	if len(snap.Settings) != 1 || snap.Settings[0].Value != "Штраф {имя}\nоплатить" {
		t.Errorf("настройки: %+v", snap.Settings)
	}

	d := Debet(snap.Residents, snap.Fines)
	if len(d) != 2 {
		t.Fatalf("debet rows: %d", len(d))
	}
	// Штрафы Ивана: 10 000 + 10 000 неоплаченных (имя без учёта регистра), 5 000 оплачен
	if d[0].FinesUnpaid != 20000 || d[0].MeetingsLeft != 2 || d[0].TotalDebt != 170000 {
		t.Errorf("дебет Ивана: %+v", d[0])
	}
	if d[1].RestEntry != 0 || d[1].TotalDebt != 0 {
		t.Errorf("отрицательный остаток должен стать нулём: %+v", d[1])
	}

	debetMiss, plMiss, checked := Check(snap, 12)
	if len(debetMiss) != 0 || len(plMiss) != 0 {
		t.Errorf("расхождения: %+v %+v", debetMiss, plMiss)
	}
	if checked < 100 {
		t.Errorf("сверено слишком мало: %d", checked)
	}
}

func TestBuildPLRules(t *testing.T) {
	snap, _, _ := Parse(sheetsFixture())
	pl := BuildPL(snap.Payments, snap.PL, 2026, 12)
	apr := pl.Months[3]
	if apr.Income["БХ Трекинг продление"] != 100000 || apr.Income["Прочие доходы"] != 10000 {
		t.Errorf("доходы апреля: %+v", apr.Income)
	}
	if apr.Dividends != 30000 || apr.Expense["Прочие расходы:"] != 5000 || apr.Expenses != 9000 {
		t.Errorf("расходы апреля: %+v div %d", apr.Expense, apr.Dividends)
	}
	if pl.Months[4].Expense["Комиссия+налог"] != 2000 {
		t.Error("«Комиссия + налог» должна попасть в «Комиссия+налог»")
	}
	if pl.Months[2].HasCash || pl.Months[3].Cash != 71000 || pl.Months[4].Cash != 119000 {
		t.Errorf("касса: мар %v, апр %d, май %d", pl.Months[2].HasCash, pl.Months[3].Cash, pl.Months[4].Cash)
	}
	if pl.Months[0].IncomeSum != 0 {
		t.Error("строка 2025 года попала в 2026")
	}
	var noCat bool
	for _, u := range pl.Unknown {
		if u.Kind == "expense" && u.Cat == "" && u.Amount == 7000 && u.Placed == "" {
			noCat = true
		}
	}
	if !noCat || len(pl.Unknown) != 3 {
		t.Errorf("неразнесённые: %+v", pl.Unknown)
	}
	// Ограничение по месяцу: май не считается при upTo = 4
	if BuildPL(snap.Payments, snap.PL, 2026, 4).Months[4].IncomeSum != 0 {
		t.Error("месяц после upTo попал в PL")
	}
	_ = time.Now
}
