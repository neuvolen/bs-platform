// legalEmail: адрес для запросов о данных (PUBLIC_CONTACT_EMAIL); без него
// на страницах только WhatsApp и Telegram клуба.
func legalEmail() string { return strings.TrimSpace(os.Getenv("PUBLIC_CONTACT_EMAIL")) }

func legalContacts() string {
	p := bsProfile
	s := `WhatsApp <a href="` + p.WALink + `">` + hx(p.WAPhone) + `</a>, Telegram <a href="` + p.Bot + `">` + hx(p.BotHandle) + `</a>`
	if e := legalEmail(); e != "" {
		s += `, e-mail <a href="mailto:` + hx(e) + `">` + hx(e) + `</a>`
	}
	return s
}

const legalCSS = `<style>.lg h2{font-size:24px;margin-top:8px}.lg h3{margin-top:22px}.lg p,.lg li{color:var(--soft)}.lg ul{padding-left:22px}.lg li{margin-top:6px}.lg .box{margin-top:14px}.lg code{font-size:13.5px;color:#fff;background:rgba(255,255,255,.06);padding:1px 6px;border-radius:6px;word-break:break-all}</style>`

func legalPage(title, desc, path, h1, lead, body string) string {
	var b strings.Builder
	ld := ldScript(obj{"@context": "https://schema.org", "@graph": []any{
		websiteNode(),
		obj{"@type": "WebPage", "@id": SiteURL + path + "#page", "url": SiteURL + path, "name": h1, "description": desc,
			"inLanguage": "ru", "isPartOf": obj{"@id": SiteURL + "/#website"}, "publisher": obj{"@id": orgID()}, "dateModified": legalUpdated},
	}})
	b.WriteString(pageHead(title, desc, SiteURL+path, "website", ld))
	b.WriteString(legalCSS)
	b.WriteString(`<main class="lg"><div class="hero"><div class="w"><span class="pill">app.bxclub.kz · редакция от ` + legalUpdated + `</span><h1>` + h1 + `</h1><p class="lead">` + lead + `</p></div></div>`)
	b.WriteString(body)
	b.WriteString(`<section><div class="w"><p>Смотрите также: <a href="/privacy">Политика конфиденциальности</a> · <a href="/terms">Условия использования</a> · <a href="/">Платформа</a> · <a href="/about">О клубе</a></p></div></section></main>` + "\n")
	b.WriteString(pageFoot())
	return b.String()
}

